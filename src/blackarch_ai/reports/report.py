"""Assemble an engagement report from stored data (deterministic, no LLM).

The report keeps three kinds of statement apart, as the spec requires:
* verified results — facts produced by an executed tool, with evidence;
* hypotheses — the agents' unverified reasoning, grouped by confidence;
* assets — what was discovered in scope.

An optional executive summary can be generated by the model, drawn only from
this data and clearly labelled as AI-written; it is never a source of new
"confirmed" findings.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime

from sqlalchemy import select

from blackarch_ai.core.context import CONFIDENCES, SEVERITIES
from blackarch_ai.storage.models import (
    Asset,
    Engagement,
    Finding,
    Plan,
    ToolExecution,
    utcnow,
)
from blackarch_ai.storage.store import Store

SEV_RANK = {s: i for i, s in enumerate(reversed(SEVERITIES))}  # critical=0 … info=4
CONF_RANK = {c: i for i, c in enumerate(reversed(CONFIDENCES))}  # high=0 … low=2


@dataclass
class EvidenceRef:
    kind: str
    path: str
    size_bytes: int
    sha256: str


@dataclass
class ExecRef:
    id: int
    operation: str
    tool: str
    target: str | None
    permission: str
    status: str
    exit_code: int | None
    argv: list[str]
    created_at: datetime
    evidence: list[EvidenceRef]


@dataclass
class FindingRef:
    title: str
    description: str
    severity: str
    confidence: str
    verified: bool
    agent: str


@dataclass
class ExecSummary:
    """Model-written summary. Advisory, clearly labelled, never a confirmed finding."""

    overview: str
    recommendations: list[str] = field(default_factory=list)
    model: str = ""


@dataclass
class ReportData:
    engagement_name: str
    objective: str
    authorized_by: str
    scope: str
    status: str
    engagement_created: datetime | None
    generated_at: datetime
    assets: list[Asset]
    verified: list[FindingRef]
    hypotheses: list[FindingRef]
    executions: list[ExecRef]
    plans: list[Plan]
    usage: object  # UsageTotals
    summary: ExecSummary | None = None

    @property
    def counts(self) -> dict[str, int]:
        return {
            "assets": len(self.assets),
            "verified": len(self.verified),
            "hypotheses": len(self.hypotheses),
            "executions": len(self.executions),
            "executions_ok": sum(e.status == "success" for e in self.executions),
        }


def _finding_ref(f: Finding) -> FindingRef:
    return FindingRef(f.title, f.description, f.severity, f.confidence, f.verified, f.agent)


def _sort_findings(items: list[FindingRef]) -> list[FindingRef]:
    return sorted(items, key=lambda f: (SEV_RANK.get(f.severity, 9),
                                        CONF_RANK.get(f.confidence, 9), f.title.lower()))


def build_report(store: Store, engagement: Engagement,
                 summary: ExecSummary | None = None) -> ReportData:
    eng_id = engagement.id
    with store.session() as s:
        assets = list(s.scalars(select(Asset).where(Asset.engagement_id == eng_id)
                                .order_by(Asset.kind, Asset.value)).all())
        findings = list(s.scalars(select(Finding).where(Finding.engagement_id == eng_id)
                                  .order_by(Finding.id)).all())
        plans = list(s.scalars(select(Plan).where(Plan.engagement_id == eng_id)
                               .order_by(Plan.id)).all())
    verified = _sort_findings([_finding_ref(f) for f in findings if f.verified])
    hypotheses = _sort_findings([_finding_ref(f) for f in findings if not f.verified])

    executions: list[ExecRef] = []
    for row in store.list_executions(engagement_id=eng_id, limit=1000):
        full = store.get_execution(row.id)
        executions.append(ExecRef(
            id=full.id, operation=full.operation, tool=full.tool, target=full.target,
            permission=full.permission, status=full.status, exit_code=full.exit_code,
            argv=list(full.argv or []), created_at=full.created_at,
            evidence=[EvidenceRef(e.kind, e.path, e.size_bytes, e.sha256)
                      for e in full.evidence],
        ))
    executions.sort(key=lambda e: e.id)

    return ReportData(
        engagement_name=engagement.name, objective=engagement.objective,
        authorized_by=engagement.authorized_by, scope=store.scope_of(engagement).summary(),
        status=engagement.status, engagement_created=engagement.created_at,
        generated_at=utcnow(), assets=assets, verified=verified, hypotheses=hypotheses,
        executions=executions, plans=plans,
        usage=store.usage_totals(engagement_id=eng_id), summary=summary,
    )
